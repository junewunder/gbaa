//! Snapshots of structured functions (`docs/structured-codegen-design.md`,
//! step 8): for each shape the printer handles, the smallest function of a
//! ROM that has it, printed as the generated crate prints it, so a change
//! to the printer shows up as a diff of a file kept in the repo
//! (`just snapshots`).

use crate::emit::{Recompiled, pretty};
use crate::func::{Ctx, Func, Plan, exits};
use crate::lower::{lower_func, structured};
use crate::plan::{How, Node};
use std::fmt::Write as _;

/// What a plan holds, for picking one of each shape.
#[derive(Default)]
struct Has {
    loops: usize,
    labeled: usize,
    regions: usize,
    /// Loops inside loops, at most.
    loop_depth: usize,
    /// Exits with three or more edges: a jump table's.
    tables: usize,
}

fn walk(seq: &[Node], depth: usize, h: &mut Has) {
    for n in seq {
        match n {
            Node::Block { exits, .. } => {
                h.tables += exits.iter().filter(|o| o.edges.len() >= 3).count();
                for e in exits.iter().flat_map(|o| &o.edges) {
                    if let How::Inline(s) = &e.how {
                        walk(s, depth, h);
                    }
                }
            }
            Node::Loop { body, .. } => {
                h.loops += 1;
                h.loop_depth = h.loop_depth.max(depth + 1);
                walk(body, depth + 1, h);
            }
            Node::Labeled { body, .. } => {
                h.labeled += 1;
                walk(body, depth, h);
            }
            Node::Region { exits, .. } => {
                h.regions += 1;
                for e in exits {
                    if let How::Inline(s) = &e.how {
                        walk(s, depth, h);
                    }
                }
            }
        }
    }
}

/// The shapes, each with what a function must have.
type Shape = (&'static str, fn(&Ctx, &Func, &Has) -> bool);

const SHAPES: &[Shape] = &[
    (
        "straight line with calls: each call compares the key it settles at with its return site",
        |c, f, h| h.loops == 0 && h.labeled == 0 && calls(c, f) >= 2,
    ),
    (
        "an if: a labeled block around one arm, the merge after it",
        |_, f, h| h.loops == 0 && h.labeled == 1 && h.regions == 0 && f.blocks.len() >= 3,
    ),
    (
        "a loop inside a labeled block (the design's WaitForVBlank shape)",
        |_, _, h| h.loops == 1 && h.labeled >= 1 && h.regions == 0,
    ),
    ("a loop inside a loop", |_, _, h| {
        h.loop_depth >= 2 && h.regions == 0
    }),
    (
        "a jump table: `match pc` over its targets and the dispatcher",
        |_, _, h| h.regions == 0 && h.tables >= 1,
    ),
    (
        "an irreducible region kept as `loop { match pc }`",
        |_, _, h| h.regions >= 1,
    ),
];

fn calls(ctx: &Ctx, f: &Func) -> usize {
    f.blocks
        .values()
        .flat_map(|gb| exits(ctx, gb))
        .filter(|x| matches!(x.plan, Plan::Call { .. }))
        .count()
}

/// The snapshot file: for each shape, the smallest structured function of
/// `r` (fewest instructions, then lowest entry) that has it.
pub fn snapshots(ctx: &Ctx, r: &Recompiled, name: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// Generated by `just snapshots` from {name}: for each shape, the smallest\n\
         // structured function that has it, as the generated crate prints it\n\
         // (docs/structured-codegen-design.md, step 8). Don't edit; rerun it.\n"
    );
    for (what, has) in SHAPES {
        let pick = r
            .funcs
            .iter()
            .filter_map(|f| {
                let (_, p) = structured(ctx, f)?;
                let mut h = Has::default();
                walk(&p.tree, 0, &mut h);
                has(ctx, f, &h).then_some(f)
            })
            .min_by_key(|f| {
                let n: usize = f.blocks.values().map(|gb| gb.insns.len()).sum();
                (n, f.entry)
            });
        let _ = writeln!(s, "// {what}");
        match pick {
            Some(f) => {
                let n: usize = f.blocks.values().map(|gb| gb.insns.len()).sum();
                let _ = writeln!(
                    s,
                    "// 0x{:08x}: {} blocks, {n} instructions\n{}",
                    f.entry,
                    f.blocks.len(),
                    pretty(lower_func(ctx, f))
                );
            }
            None => {
                let _ = writeln!(s, "// (none in this ROM)\n");
            }
        }
    }
    s
}

/// The readable snapshot (`docs/mod-view-design.md`, "The check"): each
/// function on `ctx`'s readable list, named from its source map, as the
/// generated crate prints it, and why any stays with registers in
/// `Machine`.
pub fn readable(ctx: &Ctx, name: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// Generated by `just snapshots-readable` from {name}: the functions its\n\
         // list names, printed readable (docs/mod-view-design.md, \"The readable\n\
         // form\"). Don't edit; rerun it.\n"
    );
    for &k in ctx.readable.into_iter().flatten() {
        let f = crate::func::build_func(ctx, k);
        let (body, why) = crate::lower::lower_func_checked(ctx, &f, &ctx.fn_ident(k));
        let doc = ctx.names.map(|n| crate::emit::fn_doc(n, k));
        let _ = writeln!(s, "// 0x{k:08x}");
        if let Some(w) = why {
            let _ = writeln!(s, "// registers in Machine: {w}");
        }
        let _ = writeln!(s, "{}", pretty(quote::quote!(#doc #body)));
    }
    s
}
