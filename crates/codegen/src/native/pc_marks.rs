//! Block markers kept out of the text a reader meets (unit
//! `native/lift-pc-markers`). Each block the printer prints starts with
//! `pc(0x…)` of its guest address, which a stop names in a build with the
//! crate's `guest-pc` feature (`runtime::guest_pc`) and which does nothing
//! in a plain one; as a line of its own it was one line in 12 of a game's
//! lift. [`strip`] takes them out of each module of lifted functions and
//! [`table`] keeps where they were (`pcs.txt`, beside `Cargo.toml`); the
//! crate's build script ([`BUILD_RS`]) puts them back in a copy of the
//! module under `OUT_DIR` when `guest-pc` is on, and main.rs's
//! `lifted_mod!` ([`super::modules`]) builds that copy. So a stop still names its
//! block, at the same cost, and src/ reads without them.

#[allow(dead_code)]
#[path = "pc_marks_build.rs"]
mod build;

pub use build::{Mark, TABLE, fnv, parse, restore};

/// The lifted crate's `build.rs`.
pub const BUILD_RS: &str = include_str!("pc_marks_build.rs");

pub use super::modules::is_module;

/// The key of a `pc(0x…);` statement, `s` exactly that.
fn key_of(s: &str) -> Option<u32> {
    let hex = s.strip_prefix("pc(0x")?.strip_suffix(");")?;
    (hex.len() == 8 && hex.bytes().all(|b| b.is_ascii_hexdigit()))
        .then(|| u32::from_str_radix(hex, 16).ok())
        .flatten()
}

/// `text` without its block markers, and where they were: a `pc` on a
/// line of its own, or at the end of a `match` arm's `N => {` line.
pub fn strip(text: &str) -> (String, Vec<Mark>) {
    let mut out = String::with_capacity(text.len());
    let mut marks = Vec::new();
    let mut lines = 0;
    for l in text.split_inclusive('\n') {
        let body = l.strip_suffix('\n').unwrap_or(l);
        let t = body.trim_start();
        if let Some(key) = key_of(t) {
            let indent = Some(body.len() - t.len());
            marks.push(Mark {
                line: lines,
                key,
                indent,
            });
            continue;
        }
        if let Some((head, _)) = body.rsplit_once(" pc(")
            && head.ends_with("=> {")
            && let Some(key) = key_of(&body[head.len() + 1..])
        {
            marks.push(Mark {
                line: lines,
                key,
                indent: None,
            });
            out.push_str(head);
            out.push_str(&l[body.len()..]);
        } else {
            out.push_str(l);
        }
        lines += 1;
    }
    (out, marks)
}

/// Strips every module of `files` in place, and returns their table
/// (`pcs.txt`): every module is listed, a module with no block too, since
/// the build script writes a copy of each.
pub fn strip_modules(files: &mut [(String, String)]) -> String {
    let mut t = String::from(
        "# Generated by gbaa-lift. Don't edit; rerun `just lift`.\n\
         # Each lifted block's guest pc, kept out of src/ (crates/codegen/src/native/pc_marks.rs):\n\
         # `file NAME HASH`, then `LINE KEY INDENT` (a line of its own before LINE) or\n\
         # `LINE KEY arm` (at the end of LINE), lines counted from 0 in the text without them.\n",
    );
    for (f, text) in files.iter_mut().filter(|(f, _)| is_module(f)) {
        let (plain, marks) = strip(text);
        t.push_str(&format!("file {f} {:016x}\n", fnv(&plain)));
        for m in &marks {
            match m.indent {
                Some(n) => t.push_str(&format!("{} {:08x} {n}\n", m.line, m.key)),
                None => t.push_str(&format!("{} {:08x} arm\n", m.line, m.key)),
            }
        }
        *text = plain;
    }
    t
}

#[cfg(test)]
mod tests {
    use super::*;

    const LIFTED: &str = "use crate::*;\n\npub fn f_08000100(g: &mut Game) {\n    pc(0x08000101);\n    r0 = 1;\n    loop {\n        match b {\n            3 => { pc(0x08000105);\n                r0 = 2;\n            }\n            _ => unreachable!(),\n        }\n    }\n        pc(0x08000109);\n}\n";

    #[test]
    fn strips_both_forms_and_puts_them_back() {
        let (plain, marks) = strip(LIFTED);
        assert!(!plain.contains("pc(0x"), "{plain}");
        assert!(plain.contains("            3 => {\n                r0 = 2;"));
        assert_eq!(plain.lines().count(), LIFTED.lines().count() - 2);
        assert_eq!(
            marks,
            vec![
                Mark {
                    line: 3,
                    key: 0x0800_0101,
                    indent: Some(4)
                },
                Mark {
                    line: 6,
                    key: 0x0800_0105,
                    indent: None
                },
                Mark {
                    line: 12,
                    key: 0x0800_0109,
                    indent: Some(8)
                },
            ]
        );
        assert_eq!(restore(&plain, &marks), LIFTED);
    }

    #[test]
    fn the_table_reads_back_to_the_lifted_text() {
        let mut files = vec![
            (
                "main.rs".to_string(),
                "pub fn pc(k: u32) {}\n    pc(0x08000101);\n".to_string(),
            ),
            ("m_08000100.rs".to_string(), LIFTED.to_string()),
            ("m_08000200.rs".to_string(), "use crate::*;\n".to_string()),
        ];
        let t = strip_modules(&mut files);
        assert!(
            files[0].1.contains("pc(0x08000101)"),
            "main.rs isn't a module"
        );
        let back = parse(&t).unwrap();
        assert_eq!(back.len(), 2);
        let (f, h, marks) = &back[0];
        assert_eq!((f.as_str(), *h), ("m_08000100.rs", fnv(&files[1].1)));
        assert_eq!(restore(&files[1].1, marks), LIFTED);
        assert_eq!(back[1].2, vec![]);
    }

    #[test]
    fn other_pc_text_stays() {
        let t = "    let x = pc(0x0800010);\n    3 => { pc(r0);\n";
        assert_eq!(strip(t), (t.to_string(), vec![]));
    }
}
