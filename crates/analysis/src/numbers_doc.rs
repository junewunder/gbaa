//! A generated numbers file (`docs/*.numbers.md`): the current values a
//! plan doc points to, written by the tool that measures them (`just
//! lift-metrics --write-doc FILE`, `just holes-all --write-doc FILE`) so
//! plan docs keep the plan and not a log of results. The file is a short
//! header (what wrote it, don't edit it by hand, the date and commit) and
//! the tool's table in a code block, as the terminal shows it.

use std::process::Command;

/// The file's text: a title, the generated-by line, the date and commit,
/// any notes (one paragraph each), then `table` as a code block.
pub fn render(
    title: &str,
    recipe: &str,
    date: &str,
    commit: &str,
    notes: &[String],
    table: &str,
) -> String {
    let mut s = format!(
        "# {title}\n\nGenerated by `{recipe}`; don't edit by hand. \
         Measured {date} at commit `{commit}`.\n\n"
    );
    for n in notes {
        s.push_str(n);
        s.push_str("\n\n");
    }
    s.push_str("```text\n");
    s.push_str(table.trim_end());
    s.push_str("\n```\n");
    s
}

/// Write [`render`]'s text to `path`.
pub fn write(path: &str, text: &str) -> Result<(), String> {
    std::fs::write(path, text).map_err(|e| format!("{path}: {e}"))
}

/// HEAD's short hash, `-dirty` after it when tracked files have changed;
/// `unknown` outside a git checkout.
pub fn commit() -> String {
    let git = |args: &[&str]| -> Option<String> {
        let o = Command::new("git").args(args).output().ok()?;
        o.status
            .success()
            .then(|| String::from_utf8_lossy(&o.stdout).trim().to_string())
    };
    let Some(hash) = git(&["rev-parse", "--short", "HEAD"]) else {
        return "unknown".into();
    };
    match git(&["status", "--porcelain", "--untracked-files=no"]) {
        Some(s) if !s.is_empty() => format!("{hash}-dirty"),
        _ => hash,
    }
}

/// `t`'s date (UTC) as `YYYY-MM-DD`.
pub fn date(t: std::time::SystemTime) -> String {
    let secs = t
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let (y, m, d) = civil(secs / 86_400);
    format!("{y:04}-{m:02}-{d:02}")
}

/// Days since 1970-01-01 to (year, month, day): Howard Hinnant's
/// `civil_from_days`.
fn civil(days: u64) -> (i64, u32, u32) {
    let z = days as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    let y = yoe + era * 400 + i64::from(m <= 2);
    (y, m, d)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{Duration, UNIX_EPOCH};

    #[test]
    fn dates() {
        assert_eq!(date(UNIX_EPOCH), "1970-01-01");
        assert_eq!(civil(11_016), (2000, 2, 29));
        assert_eq!(civil(11_017), (2000, 3, 1));
        let t = UNIX_EPOCH + Duration::from_secs(1_793_966_400); // 2026-11-06 12:00
        assert_eq!(date(t), "2026-11-06");
    }

    #[test]
    fn the_file_has_its_header_and_table() {
        let t = render(
            "Numbers",
            "just x --write-doc F",
            "2026-11-06",
            "abc1234",
            &["A note.".into()],
            "a  b\n1  2\n\n",
        );
        assert!(
            t.starts_with("# Numbers\n\nGenerated by `just x --write-doc F`; don't edit by hand.")
        );
        assert!(t.contains("2026-11-06") && t.contains("`abc1234`"));
        assert!(
            t.contains("\n\nA note.\n\n```text\na  b\n1  2\n```\n"),
            "{t}"
        );
    }
}
